"""Turns data/crops.csv into lib/data/crops_data.dart.

Run from the project folder after editing the CSV:
    python3 tool/csv_to_dart.py
"""
import csv, re, os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "data", "crops.csv")
OUT = os.path.join(HERE, "..", "lib", "data", "crops_data.dart")

# Word used to find each crop inside the good/bad predecessor text.
KEYWORDS = {"Cassava": "cassava", "Sweet potatoes": "sweet potato", "Maize": "maize", "Bananas": "banana",
            "Beans": "bean", "Groundnuts": "groundnut", "Tomatoes": "tomato", "Cabbages": "cabbage",
            "Rice (upland)": "rice", "Rice (paddy)": "rice", "Coffee (Robusta)": "coffee",
            "Watermelons": "watermelon", "Passion fruits (yellow)": "passion fruit",
            "Passion fruits (purple)": "passion fruit", "Pineapples": "pineapple"}

# ASSUMPTION (not in the CSV): share of the harvested weight that is sold at
# the quoted price. Groundnut yield is unshelled but the price is shelled;
# rice yield is paddy but the price is milled.
SALE_FRACTION = {"Groundnuts": 0.65, "Rice (upland)": 0.65, "Rice (paddy)": 0.65}


def level(text, table, default):
    t = text.lower().strip()
    for key, val in table:           # first match wins, so list longer keys first
        if t.startswith(key):
            return val
    return default

RESIDUE = [("medium-high", 4), ("low-medium", 2), ("high", 5), ("medium", 3), ("low", 1)]
SOM = [("strongly positive", 2.0), ("neutral to slightly negative", -0.5), ("neutral to positive", 0.5),
       ("modest positive", 0.5), ("moderate positive", 1.0), ("positive", 1.0), ("neutral", 0.0)]
PRICE_RISK = [("very high", 5.0), ("moderate-high", 3.5), ("low-moderate", 2.0), ("high", 4.0), ("moderate", 3.0), ("low", 1.0)]
STORE = [("very low", 1), ("low fresh", 3), ("low-moderate", 2), ("moderate-high", 4), ("low", 2), ("moderate", 3), ("high", 5)]


def s(text):
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def preds(text, names):
    t = text.lower()
    return [n for n in names if re.search(r"\b" + re.escape(KEYWORDS.get(n, n.lower())), t)]


rows = list(csv.DictReader(open(SRC, encoding="utf-8")))
names = [r["crop"] for r in rows]
out = ["// GENERATED by tool/csv_to_dart.py from data/crops.csv. Do not edit by hand.",
       "import '../engine/models.dart';", "", "const cropDataStatus =", "    " + s(rows[0]["verification_status"]) + ";",
       "const cropDataSource =", "    " + s(rows[0]["source"]) + ";", "", "const crops = <Crop>["]
for r in rows:
    f = lambda k: str(float(r[k] or 0))
    i = lambda k: str(int(float(r[k] or 0)))
    lst = lambda xs: "[" + ", ".join(s(x) for x in xs) + "]"
    out += ["  Crop(",
        f"    name: {s(r['crop'])}, family: {s(r['family'])}, scientificName: {s(r['scientific_name'])},",
        f"    cropType: {s(r['crop_type'])}, perennial: {'true' if r['life_cycle'] == 'perennial' else 'false'},",
        f"    waterMin: {f('water_min_mm')}, waterMax: {f('water_max_mm')}, tempMin: {f('temp_min_c')}, tempMax: {f('temp_max_c')},",
        f"    daysMin: {i('days_min')}, daysMax: {i('days_max')}, slots: {i('rotation_slots_occupied')},",
        f"    nitrogenEffect: {s(r['nitrogen_effect'])}, nFixMin: {f('n_fixation_kg_ha_min')}, nFixMax: {f('n_fixation_kg_ha_max')},",
        f"    nutrientDemand: {i('nutrient_demand_1to5')}, drought: {i('drought_tolerance_1to5')}, waterlogging: {i('waterlogging_tolerance_1to5')},",
        f"    groundCover: {i('ground_cover_score_1to5')}, residue: {s(r['residue_biomass_returned'])}, residueScore: {level(r['residue_biomass_returned'], RESIDUE, 3)},",
        f"    rootDepth: {s(r['root_depth'])}, somEffect: {s(r['soil_organic_matter_effect'])}, somScore: {level(r['soil_organic_matter_effect'], SOM, 0.0)},",
        f"    pests: {s(r['main_pests_diseases'])},",
        f"    hostGroup: {s(r['host_group'])}, breakSeasons: {i('break_period_seasons')},",
        f"    yieldMin: {f('yield_t_ha_min')}, yieldMax: {f('yield_t_ha_max')}, yieldBasis: {s(r['yield_basis'])},",
        f"    costMin: {f('input_labour_cost_ugx_ha_min')}, costMax: {f('input_labour_cost_ugx_ha_max')},",
        f"    priceMin: {f('price_per_kg_min_ugx')}, priceMax: {f('price_per_kg_max_ugx')}, marketUnit: {s(r['market_unit'])},",
        f"    marketNotes: {s(r['market_notes'])},",
        f"    priceVariability: {s(r['price_variability'])}, priceRisk: {level(r['price_variability'], PRICE_RISK, 3.0)},",
        f"    marketAccess: {s(r['market_access'])}, storability: {s(r['storability'])}, storeScore: {level(r['storability'], STORE, 3)},",
        f"    kcalPerKg: {f('calories_kcal_per_kg')}, proteinPerKg: {f('protein_g_per_kg')}, staple: {s(r['staple_status'])},",
        f"    plantingWindow: {s(r['planting_window'])},",
        f"    goodAfter: {lst(preds(r['good_predecessors'], names))},",
        f"    badAfter: {lst(preds(r['bad_predecessors'], names))},",
        f"    goodAfterText: {s(r['good_predecessors'])},",
        f"    badAfterText: {s(r['bad_predecessors'])},",
        f"    confidence: {s(r['confidence'])}, saleFraction: {SALE_FRACTION.get(r['crop'], 1.0)},",
        f"    needsFlooding: {'true' if 'flood' in r['planting_window'].lower() else 'false'},",
        "  ),"]
out += ["];", ""]
open(OUT, "w", encoding="utf-8").write("\n".join(out))
print("wrote", len(rows), "crops")
