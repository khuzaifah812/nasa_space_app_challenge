class Lang {
  Lang._();

  /// The current language code. Change it with [set].
  static final notifier = ValueNotifier<String>('en');
  static String get code => notifier.value;
  static bool get rtl => code == 'ar';

  static void set(String code) {
    if (_tables.containsKey(code)) notifier.value = code;
  }

  /// The code for a language name from the country list, or null if the
  /// app has no translation for it yet.
  static String? codeFor(String name) => languages[name];
}

/// The text for [key] in the current language.
String t(String key) => _tables[Lang.code]?[key] ?? _tables['en']![key] ?? key;

/// [t] with {n}-style holes filled in: tf('stepOf', {'n': 1, 'total': 4}).
String tf(String key, Map<String, Object> values) {
  var s = t(key);
  values.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}

